def q(s):
    return "'" + str(s).replace("'", "''") + "'"

lines = ['-- Generated by scripts/make_seed.py. Safe to re-run: uses INSERT OR IGNORE.']
colors = json.dumps(['Black'])
for i, (sku, name, price, cat, sizes, img, summary, specs) in enumerate(P):
    lines.append(
        "INSERT OR IGNORE INTO products (sku,name,category,price,summary,specs,image,colors,sizes,active,sort_order) VALUES (%s,%s,%s,%d,%s,%s,%s,%s,%s,1,%d);"
        % (q(sku), q(name), q(cat), price, q(summary), q(json.dumps(specs)), q('/assets/images/' + img), q(colors), q(json.dumps(sizes)), i)
    )
    for s in sizes:
        lines.append(
            "INSERT OR IGNORE INTO variants (product_id,size,color,stock) SELECT id,%s,'Black',NULL FROM products WHERE sku=%s;" % (q(s), q(sku))
        )

